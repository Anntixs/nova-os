// 5x7 uppercase bootstrap font, expanded into the high bits of an 8x8 cell.
pub fn glyph(c: u8) -> [u8; 8] {
    let rows: [u8; 7] = match c.to_ascii_uppercase() {
        b'A' => [14, 17, 17, 31, 17, 17, 17],
        b'B' => [30, 17, 17, 30, 17, 17, 30],
        b'C' => [14, 17, 16, 16, 16, 17, 14],
        b'D' => [30, 17, 17, 17, 17, 17, 30],
        b'E' => [31, 16, 16, 30, 16, 16, 31],
        b'F' => [31, 16, 16, 30, 16, 16, 16],
        b'G' => [14, 17, 16, 23, 17, 17, 14],
        b'H' => [17, 17, 17, 31, 17, 17, 17],
        b'I' => [31, 4, 4, 4, 4, 4, 31],
        b'J' => [7, 2, 2, 2, 18, 18, 12],
        b'K' => [17, 18, 20, 24, 20, 18, 17],
        b'L' => [16, 16, 16, 16, 16, 16, 31],
        b'M' => [17, 27, 21, 21, 17, 17, 17],
        b'N' => [17, 25, 21, 19, 17, 17, 17],
        b'O' => [14, 17, 17, 17, 17, 17, 14],
        b'P' => [30, 17, 17, 30, 16, 16, 16],
        b'Q' => [14, 17, 17, 17, 21, 18, 13],
        b'R' => [30, 17, 17, 30, 20, 18, 17],
        b'S' => [15, 16, 16, 14, 1, 1, 30],
        b'T' => [31, 4, 4, 4, 4, 4, 4],
        b'U' => [17, 17, 17, 17, 17, 17, 14],
        b'V' => [17, 17, 17, 17, 17, 10, 4],
        b'W' => [17, 17, 17, 21, 21, 21, 10],
        b'X' => [17, 17, 10, 4, 10, 17, 17],
        b'Y' => [17, 17, 10, 4, 4, 4, 4],
        b'Z' => [31, 1, 2, 4, 8, 16, 31],
        b'0' => [14, 17, 19, 21, 25, 17, 14],
        b'1' => [4, 12, 4, 4, 4, 4, 14],
        b'2' => [14, 17, 1, 2, 4, 8, 31],
        b'3' => [30, 1, 1, 14, 1, 1, 30],
        b'4' => [2, 6, 10, 18, 31, 2, 2],
        b'5' => [31, 16, 30, 1, 1, 17, 14],
        b'6' => [6, 8, 16, 30, 17, 17, 14],
        b'7' => [31, 1, 2, 4, 8, 8, 8],
        b'8' => [14, 17, 17, 14, 17, 17, 14],
        b'9' => [14, 17, 17, 15, 1, 2, 12],
        b'.' => [0, 0, 0, 0, 0, 12, 12],
        b'_' => [0, 0, 0, 0, 0, 0, 31],
        b':' => [0, 12, 12, 0, 12, 12, 0],
        b'/' => [1, 1, 2, 4, 8, 16, 16],
        b'\\' => [16, 16, 8, 4, 2, 1, 1],
        b'-' => [0, 0, 0, 31, 0, 0, 0],
        b'$' => [4, 15, 20, 14, 5, 30, 4],
        b'?' => [14, 17, 1, 2, 4, 0, 4],
        b'!' => [4, 4, 4, 4, 4, 0, 4],
        b'=' => [0, 31, 0, 31, 0, 0, 0],
        b'(' => [2, 4, 8, 8, 8, 4, 2],
        b')' => [8, 4, 2, 2, 2, 4, 8],
        b'\'' => [4, 4, 8, 0, 0, 0, 0],
        b'"' => [10, 10, 0, 0, 0, 0, 0],
        b' ' => [0; 7],
        _ => [31, 17, 2, 4, 4, 0, 4],
    };
    let mut out = [0; 8];
    let mut i = 0;
    while i < 7 {
        out[i] = rows[i] << 3;
        i += 1;
    }
    out
}
